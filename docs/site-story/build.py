def hero():
	cx, cy = 600, 315
	orbit = [
		("browser", 200, 160), ("notebook", 150, 330), ("messages", 230, 490),
		("code", 1000, 160), ("calendar", 1050, 330), ("sparkle", 970, 490),
	]
	lines = []
	for _, x, y in orbit:
		dx, dy = cx - x, cy - y
		d = (dx * dx + dy * dy) ** 0.5
		lines.append(
			f'<line x1="{x + dx / d * 80}" y1="{y + dy / d * 80}" x2="{cx - dx / d * 180}" y2="{cy - dy / d * 180}" class="ink thin dash" />'
		)
	icons = "".join(icon(n, x, y, 120) for n, x, y in orbit)
	body = f"""
	{''.join(lines)}
	{icons}
	<circle cx="{cx}" cy="{cy}" r="150" class="ink fill" />
	{avatar(cx, cy, 128)}
	"""
	return page(1200, 630, body)


