	lx, rx, w = 140, 560, 200
	parts = [text(lx + w / 2, 142, "Vector order", cls="small"), text(rx + w / 2, 142, "Reranked", cls="small")]
	for i, item in enumerate(before):
		j = after.index(item)
		ya, yb = y0 + i * step + 17, y0 + j * step + 17
