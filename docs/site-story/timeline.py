"""Generates timeline.html. Add a row here when the site changes, then run ./render.sh.

Commit counts come from:
  git log --format='%ad' --date=format:'%Y-%m' | sort | uniq -c
"""

from pathlib import Path

# (date line 1, date line 2, commits that month, headline, detail lines)
ROWS = [
	("Feb 2024", None, 18, "First version", [
		"GPT-3.5 Turbo, streaming replies, and function",
		"calls that move you around the site",
	]),
	("Mar 2024", None, 20, "It learns to look things up", [
		"Pinecone, LangChain, text-embedding-3-small,",
		"LangSmith tracing",
	]),
	("Apr 2024", None, 11, "Polish", ["Better loading states, cleaner logging"]),
	("May 2024 –", "Oct 2025", 0, "Quiet stretch", ["About 18 months with no commits. The site just ran"]),
	("Nov 2025", None, 1, "Landing page refresh", ["A new home page headline"]),
	("Mar 2026", None, 93, "The rebuild", [
		"Qdrant, AI SDK, Svelte 5, PostHog, suggestion chips,",
		"iMessage. Claude Code starts committing alongside Hunter",
	]),
	("Apr 2026", None, 4, "Finding its voice", ["Few-shot voice examples, a ban list for AI-isms"]),
	("Aug 2026", None, 24, "New tools", [
		"GPT-5.6, reading its own GitHub repo, Hunter’s",
		"calendar, a cron that keeps Qdrant awake",
	]),
	("Oct 2026", None, 22, "Faster and friendlier", [
		"GPT-6, adaptive lanes, AI SDK 7, Cohere rerank,",
		"a sketchy thinking avatar",
	]),
]

AXIS_X = 250
MAX_BAR = 200
ROW_H = 92
TOP = 210
TEXT_X = 520

scale = MAX_BAR / max(r[2] for r in ROWS)
height = TOP + (len(ROWS) - 1) * ROW_H + 100
out = []
for i, (date, date2, commits, headline, details) in enumerate(ROWS):
	y = TOP + i * ROW_H
	out.append(f'<text x="60" y="{y}" class="date">{date}</text>')
	if date2:
		out.append(f'<text x="60" y="{y + 24}" class="date">{date2}</text>')
	if commits == 0:
		# No bar for an empty stretch, so it can't be misread as a big one
		out.append(f'<text x="{AXIS_X + 12}" y="{y - 3}" class="val">0</text>')
	else:
		w = max(4, round(commits * scale, 1))
		# Square at the axis, 4px rounded at the data end
		out.append(
			f'<path d="M{AXIS_X},{y - 20} h{w - 4} a4,4 0 0 1 4,4 v14 a4,4 0 0 1 -4,4 '
			f'h-{w - 4} z" fill="#ad6e5e" />'
		)
		out.append(f'<text x="{AXIS_X + w + 10}" y="{y - 3}" class="val">{commits}</text>')
	out.append(f'<text x="{TEXT_X}" y="{y}" class="h" style="font-size:21px">{headline}</text>')
	for j, line in enumerate(details):
		out.append(f'<text x="{TEXT_X}" y="{y + 28 + j * 24}" class="p" style="font-size:17px">{line}</text>')

body = "\n\t".join(out)
html = f"""<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<link rel="stylesheet" href="_shared.css" />
<style>
	.date {{ font-size: 19px; font-weight: 500; fill: #44403c; }}
	.val {{ font-size: 16px; font-weight: 500; fill: #57534e; }}
</style>
</head>
<body>
<svg width="1200" height="{height}" viewBox="0 0 1200 {height}" xmlns="http://www.w3.org/2000/svg">
	<!-- Generated by timeline.py, edit the rows there -->
	<text x="60" y="82" class="title">How HuntBot <tspan class="serif">got here</tspan></text>
	<text x="60" y="120" class="sub">Commits per month, and what changed</text>
	<text x="{AXIS_X}" y="160" class="label">Commits</text>
	<text x="{TEXT_X}" y="160" class="label">What changed</text>
	<line x1="{AXIS_X}" y1="178" x2="{AXIS_X}" y2="{height - 40}" stroke="#a8a29e" stroke-width="1.5" />
	{body}
</svg>
</body>
</html>
"""

Path(__file__).with_name("timeline.html").write_text(html)
